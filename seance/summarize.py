"""Build the human-readable outputs from results/ and ledger/ (no model calls):

  results/SUMMARY.md        every run, every number, cost from the ledger
  docs/index.html           the graveyard page (GitHub Pages)
  docs/assets/raised.png    chart: target tests passing on 3.13, before and after

    python seance/summarize.py
"""

import collections
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
REPO_URL = "https://github.com/Bowen1314/pip-seance"
MODEL_SHORT = {"deepseek-ai/DeepSeek-V4-Flash-0731": "DeepSeek V4 Flash",
               "Qwen/Qwen3-30B-A3B-Instruct-2507": "Qwen3-30B-A3B",
               "zai-org/GLM-5.3-Flash": "GLM-5.3-Flash"}


def load():
    ghosts = {g["project"]: g for g in json.load(open(RES / "ghosts.json"))["ghosts"]}
    census = json.load(open(RES / "census.json"))
    audit = json.load(open(RES / "audit.json"))
    ledger = [json.loads(l) for l in open(ROOT / "ledger" / "spend.jsonl")]
    per_run = collections.defaultdict(float)
    span = {}
    for r in ledger:
        per_run[r["run"]] += r["usd"]
        a, b = span.get(r["run"], (r["ts"], r["ts"]))
        span[r["run"]] = (min(a, r["ts"]), max(b, r["ts"]))
    runs = {}
    for rd in sorted((RES / "runs").iterdir()):
        if (rd / "run.json").exists():
            r = json.load(open(rd / "run.json"))
            r["usd_all"] = per_run.get(r["run"], 0.0)
            r["attempt_log"] = (rd / "attempts.log").read_text().strip().splitlines() if (rd / "attempts.log").exists() else []
            runs[r["run"]] = r
    return ghosts, census, audit, ledger, runs


def kind(run):
    return run.split("-")[0]


def summary_md(ghosts, census, audit, ledger, runs):
    total = sum(r["usd"] for r in ledger)
    st = census["status"]
    alive38 = st.get("ghost", 0) + st.get("still_alive", 0)
    L = ["# pip-seance results", "",
         f"Generated by `seance/summarize.py` from `results/` and `ledger/spend.jsonl`.", "",
         "## The census", "",
         f"- Source: the 15,000 most-downloaded PyPI projects of the last 30 days "
         f"([hugovk/top-pypi-packages]({census['source']['source']}), updated {census['source']['dataset_updated'][:10]}).",
         f"- **{census['undead']}** had not uploaded a file since before {census['source']['cutoff']} (the undead).",
         f"- {st.get('no_sdist', 0)} had no sdist, {st.get('no_tests', 0)} shipped no tests in the sdist, "
         f"{st.get('native_code', 0)} had C/Cython code, {st.get('not_alive_on_38', 0)} had fewer than 3 tests passing on Python 3.8 "
         f"(mostly missing third-party test dependencies).",
         f"- **{alive38}** passed their own tests on Python 3.8. Of those, {st.get('still_alive', 0)} still pass on 3.13 and "
         f"**{st.get('ghost', 0)} are ghosts**: some tests that passed on 3.8 fail on 3.13.", "",
         "## The ghosts", "",
         "| package | last upload | downloads (30 days) | target tests | passing on 3.13 | cause of death |",
         "|---|---|---|---|---|---|"]
    for p, g in ghosts.items():
        L.append(f"| {p} {g['version']} | {g['last_upload'][:10]} | {g['downloads_30d']:,} | {len(g['alive_38'])} | "
                 f"{len(g['alive_38']) - len(g['lost_on_313'])} | {audit['cause_of_death'].get(p, '')} |")
    L += ["", "## Every run", "",
          "Cost is the sum of the run's rows in the ledger (all attempts), at Nebius list prices with no cache discount.", "",
          "| run | status | 3.13 after | 3.8 after | protected files changed | files / lines changed | steps | cost | attempts | stopped | review |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, r in runs.items():
        v = r["verdict"]
        rev = audit["revivals"].get(name, {})
        L.append(f"| [{name}](runs/{name}/EPITAPH.md) | {r['status']} | {v['py313']['passing']}/{v['py313']['targets']} | "
                 f"{v['py38']['passing']}/{v['py38']['targets']} | {len(v['protected_changed'])} | {v['files_changed']} / {v['diff_lines_changed']} | "
                 f"{r['seance']['steps']} | ${r['usd_all']:.4f} | {r['attempts']} | {r['seance']['stopped']} | {rev.get('verdict', '')} |")
    L += ["", "## Per model (bench runs only)", "",
          "| model | ghosts tried | revived | revived, sound per review | broke 3.8 | cost | cost per revival |", "|---|---|---|---|---|---|---|"]
    for m, short in MODEL_SHORT.items():
        rs = [r for n, r in runs.items() if kind(n) == "bench" and r["model"] == m]
        if not rs:
            continue
        rev = [r for r in rs if r["status"] == "REVIVED"]
        sound = [r for r in rev if audit["revivals"].get(r["run"], {}).get("verdict") == "sound"]
        broke = [r for r in rs if r["verdict"]["py38"]["passing"] < r["verdict"]["py38"]["targets"]]
        cost = sum(r["usd_all"] for r in rs)
        L.append(f"| {short} | {len(rs)} | {len(rev)} | {len(sound)} | {len(broke)} | ${cost:.4f} | "
                 f"{'$%.4f' % (cost / len(rev)) if rev else 'n/a'} |")
    by_kind = collections.defaultdict(float)
    for r in ledger:
        by_kind[kind(r["run"])] += r["usd"]
    L += ["", "## Spend", "", f"Ledger total: **${total:.4f}** over {len(ledger)} model calls (cap: $1.00).", ""]
    for k, v in sorted(by_kind.items(), key=lambda x: -x[1]):
        L.append(f"- {k}: ${v:.4f}")
    (RES / "SUMMARY.md").write_text("\n".join(L) + "\n")
    return total


def chart(ghosts, runs):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    order = list(ghosts)
    series = [("before (pristine)", None, "#5b5b6b"),
              ("DeepSeek V4 Flash", "bench-deepseek-v4-flash-", "#f2a541"),
              ("Qwen3-30B-A3B", "bench-qwen3-30b-a3b-", "#7fb7be"),
              ("GLM-5.3-Flash", "bench-glm-5.3-flash-", "#b07bac"),
              ("DeepSeek, round 2 (better test feedback)", "round2-deepseek-v4-flash-", "#e8e1d0")]
    fig, ax = plt.subplots(figsize=(10, 5.2), dpi=150)
    fig.patch.set_facecolor("#14121a")
    ax.set_facecolor("#14121a")
    w = 0.16
    for i, (label, prefix, color) in enumerate(series):
        xs, ys = [], []
        for j, p in enumerate(order):
            g = ghosts[p]
            if prefix is None:
                y = (len(g["alive_38"]) - len(g["lost_on_313"])) / len(g["alive_38"])
            else:
                r = runs.get(prefix + p)
                if not r:
                    continue
                y = r["verdict"]["py313"]["passing"] / r["verdict"]["py313"]["targets"]
            xs.append(j + (i - 2) * w)
            ys.append(100 * y)
        ax.bar(xs, ys, w, label=label, color=color)
    ax.set_xticks(range(len(order)))
    ax.set_xticklabels(order, rotation=30, ha="right", color="#e8e1d0")
    ax.set_ylabel("target tests passing on Python 3.13 (%)", color="#e8e1d0")
    ax.set_ylim(0, 105)
    ax.tick_params(colors="#e8e1d0")
    for s in ax.spines.values():
        s.set_color("#3a3646")
    ax.set_title("Ten abandoned PyPI packages: their own tests on Python 3.13, before and after a seance",
                 color="#e8e1d0", fontsize=11)
    ax.legend(facecolor="#1e1b26", edgecolor="#3a3646", labelcolor="#e8e1d0", fontsize=8, loc="upper center",
              bbox_to_anchor=(0.5, -0.28), ncol=3)
    fig.tight_layout()
    out = ROOT / "docs" / "assets" / "raised.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, facecolor=fig.get_facecolor())


def graveyard(ghosts, census, audit, runs, total):
    def badge(r):
        if not r:
            return ""
        s = r["status"]
        cls = {"REVIVED": "rev", "STIRRED": "stir"}.get(s, "dead")
        v = r["verdict"]["py313"]
        short = MODEL_SHORT.get(r["model"], r["model"])
        tag = " (round 2)" if r["run"].startswith("round2") else ""
        return (f'<a class="b {cls}" href="{REPO_URL}/blob/main/results/runs/{r["run"]}/EPITAPH.md">'
                f'{html.escape(short + tag)}: {s.lower()} {v["passing"]}/{v["targets"]} · ${r["usd_all"]:.3f}</a>')

    stones = []
    for p, g in ghosts.items():
        rs = [runs.get(f"{pre}-{p}") for pre in ("bench-deepseek-v4-flash", "bench-qwen3-30b-a3b",
                                                  "bench-glm-5.3-flash", "round2-deepseek-v4-flash")]
        risen = any(r and r["status"] == "REVIVED" for r in rs)
        stones.append(f'''<article class="stone{' risen' if risen else ''}">
<h2>{html.escape(p)}</h2>
<p class="dates">{html.escape(g['version'])} · last upload {g['last_upload'][:10]}</p>
<p class="dl">{g['downloads_30d']:,} downloads in the last 30 days</p>
<p class="cod">{html.escape(audit['cause_of_death'].get(p, ''))}</p>
<p class="tests">{len(g['alive_38'])} tests passed on Python 3.8 · {len(g['alive_38']) - len(g['lost_on_313'])} pass on 3.13</p>
<div class="badges">{''.join(badge(r) for r in rs if r)}</div>
</article>''')
    st = census["status"]
    page = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>pip-seance: the graveyard</title>
<style>
:root{{--bg:#14121a;--stone:#2a2732;--ink:#e8e1d0;--dim:#9a93a6;--gold:#f2a541;--teal:#7fb7be;--red:#c8695a}}
*{{box-sizing:border-box}}body{{margin:0;background:var(--bg);color:var(--ink);font:15px/1.5 ui-sans-serif,system-ui,-apple-system,Segoe UI,sans-serif}}
header{{max-width:1100px;margin:0 auto;padding:40px 24px 8px}}h1{{font:600 34px/1.1 Georgia,serif;margin:0 0 8px;letter-spacing:.5px}}
header p{{color:var(--dim);max-width:780px;margin:6px 0}}header b{{color:var(--ink)}}
main{{max-width:1100px;margin:0 auto;padding:16px 24px 48px;display:grid;grid-template-columns:repeat(auto-fill,minmax(250px,1fr));gap:18px}}
.stone{{background:var(--stone);border-radius:110px 110px 10px 10px;padding:36px 20px 18px;text-align:center;border-bottom:6px solid #1c1a22;position:relative}}
.stone.risen{{box-shadow:0 0 0 2px var(--gold),0 0 28px rgba(242,165,65,.25)}}
.stone h2{{font:600 21px Georgia,serif;margin:0 0 4px}}.dates,.dl,.tests{{color:var(--dim);font-size:13px;margin:2px 0}}
.cod{{font-size:13px;margin:12px 0;min-height:60px}}.badges{{display:flex;flex-direction:column;gap:6px}}
.b{{display:block;font-size:12px;padding:4px 8px;border-radius:6px;text-decoration:none;color:var(--bg)}}
.rev{{background:var(--gold)}}.stir{{background:var(--teal)}}.dead{{background:#4a4556;color:var(--ink)}}
footer{{max-width:1100px;margin:0 auto;padding:0 24px 40px;color:var(--dim);font-size:13px}}a{{color:var(--gold)}}
</style></head><body>
<header><h1>pip-seance · the graveyard</h1>
<p>Of the 15,000 most-downloaded PyPI projects, <b>{census['undead']}</b> have not uploaded a file since before 2018.
<b>{st.get('ghost', 0) + st.get('still_alive', 0)}</b> of those still passed their own tests on Python 3.8.
<b>{st.get('ghost', 0)}</b> fail them on Python 3.13. These are their headstones.</p>
<p>Each badge is one seance: an open-weight model (Mastra agent, Nebius Token Factory) editing library code only, inside a Temporal workflow,
judged by the package's untouched original tests. Gold stones were raised. Click a badge for the epitaph.</p></header>
<main>
{chr(10).join(stones)}
</main>
<footer>Total spend for every model call in the project: ${total:.2f}. Code, ledger, transcripts and diffs:
<a href="{REPO_URL}">{REPO_URL}</a>. Generated by <code>seance/summarize.py</code>.</footer>
</body></html>
'''
    (ROOT / "docs" / "index.html").write_text(page)


def main():
    ghosts, census, audit, ledger, runs = load()
    total = summary_md(ghosts, census, audit, ledger, runs)
    chart(ghosts, runs)
    graveyard(ghosts, census, audit, runs, total)
    print(f"{len(runs)} runs, ledger ${total:.4f}")


if __name__ == "__main__":
    main()
